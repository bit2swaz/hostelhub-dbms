-- HostelHub: 01_schema.sql
-- Run as hostelhub. Creates all tables and constraints (PRD section 5.1).
-- Every constraint is named: pk_, fk_, uq_, ck_ (NOT NULL constraints are ck_..._nn).
-- When several CHECKs fail, Oracle reports the last one defined. Combined (table-level)
-- checks are therefore listed before the single-column checks they overlap with, so the
-- most specific constraint name is the one reported.

SET DEFINE OFF

CREATE TABLE hostel_user (
  user_id    NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ck_hostel_user_id_nn NOT NULL,
  full_name  VARCHAR2(100) CONSTRAINT ck_hostel_user_full_name_nn NOT NULL,
  email      VARCHAR2(120) CONSTRAINT ck_hostel_user_email_nn NOT NULL,
  phone      VARCHAR2(10),
  password   VARCHAR2(200) CONSTRAINT ck_hostel_user_password_nn NOT NULL,
  user_role  VARCHAR2(10)  CONSTRAINT ck_hostel_user_role_nn NOT NULL,
  CONSTRAINT pk_hostel_user PRIMARY KEY (user_id),
  CONSTRAINT uq_hostel_user_email UNIQUE (email),
  CONSTRAINT ck_hostel_user_email CHECK (REGEXP_LIKE(email, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$', 'c')),
  CONSTRAINT ck_hostel_user_phone CHECK (REGEXP_LIKE(phone, '^[0-9]{10}$')),
  CONSTRAINT ck_hostel_user_role CHECK (user_role IN ('STUDENT', 'WARDEN'))
);

CREATE TABLE student (
  user_id       NUMBER,
  reg_no        VARCHAR2(10) CONSTRAINT ck_student_reg_no_nn NOT NULL,
  gender        CHAR(1)      CONSTRAINT ck_student_gender_nn NOT NULL,
  programme     VARCHAR2(60) CONSTRAINT ck_student_programme_nn NOT NULL,
  year_of_study NUMBER(1)    CONSTRAINT ck_student_year_of_study_nn NOT NULL,
  CONSTRAINT pk_student PRIMARY KEY (user_id),
  CONSTRAINT fk_student_user FOREIGN KEY (user_id) REFERENCES hostel_user (user_id) ON DELETE CASCADE,
  CONSTRAINT uq_student_reg_no UNIQUE (reg_no),
  CONSTRAINT ck_student_reg_no CHECK (REGEXP_LIKE(reg_no, '^[0-9]{2}[A-Z]{3}[0-9]{4}$', 'c')),
  CONSTRAINT ck_student_gender CHECK (gender IN ('M', 'F')),
  CONSTRAINT ck_student_year_of_study CHECK (year_of_study BETWEEN 1 AND 5)
);

CREATE TABLE block (
  block_id    NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ck_block_id_nn NOT NULL,
  block_name  VARCHAR2(30) CONSTRAINT ck_block_name_nn NOT NULL,
  gender_type CHAR(1)      CONSTRAINT ck_block_gender_type_nn NOT NULL,
  num_floors  NUMBER(2)    CONSTRAINT ck_block_num_floors_nn NOT NULL,
  CONSTRAINT pk_block PRIMARY KEY (block_id),
  CONSTRAINT uq_block_name UNIQUE (block_name),
  CONSTRAINT ck_block_gender_type CHECK (gender_type IN ('M', 'F')),
  CONSTRAINT ck_block_num_floors CHECK (num_floors BETWEEN 1 AND 20)
);

CREATE TABLE warden (
  user_id   NUMBER,
  block_id  NUMBER CONSTRAINT ck_warden_block_id_nn NOT NULL,
  office_no VARCHAR2(10),
  CONSTRAINT pk_warden PRIMARY KEY (user_id),
  CONSTRAINT fk_warden_user FOREIGN KEY (user_id) REFERENCES hostel_user (user_id) ON DELETE CASCADE,
  CONSTRAINT uq_warden_block UNIQUE (block_id),
  CONSTRAINT fk_warden_block FOREIGN KEY (block_id) REFERENCES block (block_id)
);

CREATE TABLE room (
  block_id  NUMBER,
  room_no   VARCHAR2(6),
  floor_no  NUMBER(2)    CONSTRAINT ck_room_floor_no_nn NOT NULL,
  room_type VARCHAR2(10) CONSTRAINT ck_room_room_type_nn NOT NULL,
  capacity  NUMBER(1)    CONSTRAINT ck_room_capacity_nn NOT NULL,
  CONSTRAINT pk_room PRIMARY KEY (block_id, room_no),
  CONSTRAINT fk_room_block FOREIGN KEY (block_id) REFERENCES block (block_id),
  CONSTRAINT ck_room_capacity_type CHECK (
       (room_type = 'SINGLE' AND capacity = 1)
    OR (room_type = 'DOUBLE' AND capacity = 2)
    OR (room_type = 'TRIPLE' AND capacity = 3)
    OR (room_type = 'QUAD'   AND capacity = 4)),
  CONSTRAINT ck_room_floor_no CHECK (floor_no >= 0),
  CONSTRAINT ck_room_room_type CHECK (room_type IN ('SINGLE', 'DOUBLE', 'TRIPLE', 'QUAD')),
  CONSTRAINT ck_room_capacity CHECK (capacity BETWEEN 1 AND 4)
);

CREATE TABLE allocation (
  alloc_id    NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ck_allocation_alloc_id_nn NOT NULL,
  student_id  NUMBER      CONSTRAINT ck_allocation_student_id_nn NOT NULL,
  block_id    NUMBER      CONSTRAINT ck_allocation_block_id_nn NOT NULL,
  room_no     VARCHAR2(6) CONSTRAINT ck_allocation_room_no_nn NOT NULL,
  approved_by NUMBER      CONSTRAINT ck_allocation_approved_by_nn NOT NULL,
  start_date  DATE DEFAULT SYSDATE CONSTRAINT ck_allocation_start_date_nn NOT NULL,
  end_date    DATE,
  status      VARCHAR2(8) CONSTRAINT ck_allocation_status_nn NOT NULL,
  CONSTRAINT pk_allocation PRIMARY KEY (alloc_id),
  CONSTRAINT fk_allocation_student FOREIGN KEY (student_id) REFERENCES student (user_id),
  CONSTRAINT fk_allocation_room FOREIGN KEY (block_id, room_no) REFERENCES room (block_id, room_no),
  CONSTRAINT fk_allocation_warden FOREIGN KEY (approved_by) REFERENCES warden (user_id),
  CONSTRAINT ck_allocation_status_end CHECK (
       (status = 'ACTIVE'  AND end_date IS NULL)
    OR (status = 'VACATED' AND end_date IS NOT NULL)),
  CONSTRAINT ck_allocation_status CHECK (status IN ('ACTIVE', 'VACATED')),
  CONSTRAINT ck_allocation_dates CHECK (end_date >= start_date)
);

-- BR-2: at most one ACTIVE allocation per student.
CREATE UNIQUE INDEX ux_alloc_one_active ON allocation (CASE WHEN status = 'ACTIVE' THEN student_id END);

CREATE TABLE category (
  category_id   NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ck_category_id_nn NOT NULL,
  category_name VARCHAR2(30) CONSTRAINT ck_category_name_nn NOT NULL,
  sla_days      NUMBER(3)    CONSTRAINT ck_category_sla_days_nn NOT NULL,
  CONSTRAINT pk_category PRIMARY KEY (category_id),
  CONSTRAINT uq_category_name UNIQUE (category_name),
  CONSTRAINT ck_category_sla_days CHECK (sla_days > 0)
);

CREATE TABLE staff (
  staff_id    NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ck_staff_id_nn NOT NULL,
  full_name   VARCHAR2(100) CONSTRAINT ck_staff_full_name_nn NOT NULL,
  phone       VARCHAR2(10),
  category_id NUMBER        CONSTRAINT ck_staff_category_id_nn NOT NULL,
  CONSTRAINT pk_staff PRIMARY KEY (staff_id),
  CONSTRAINT fk_staff_category FOREIGN KEY (category_id) REFERENCES category (category_id),
  CONSTRAINT ck_staff_phone CHECK (REGEXP_LIKE(phone, '^[0-9]{10}$'))
);

CREATE TABLE complaint (
  complaint_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ck_complaint_id_nn NOT NULL,
  student_id   NUMBER        CONSTRAINT ck_complaint_student_id_nn NOT NULL,
  block_id     NUMBER        CONSTRAINT ck_complaint_block_id_nn NOT NULL,
  room_no      VARCHAR2(6)   CONSTRAINT ck_complaint_room_no_nn NOT NULL,
  category_id  NUMBER        CONSTRAINT ck_complaint_category_id_nn NOT NULL,
  staff_id     NUMBER,
  description  VARCHAR2(500) CONSTRAINT ck_complaint_description_nn NOT NULL,
  status       VARCHAR2(12) DEFAULT 'OPEN' CONSTRAINT ck_complaint_status_nn NOT NULL,
  raised_on    DATE DEFAULT SYSDATE CONSTRAINT ck_complaint_raised_on_nn NOT NULL,
  resolved_on  DATE,
  CONSTRAINT pk_complaint PRIMARY KEY (complaint_id),
  CONSTRAINT fk_complaint_student FOREIGN KEY (student_id) REFERENCES student (user_id),
  CONSTRAINT fk_complaint_room FOREIGN KEY (block_id, room_no) REFERENCES room (block_id, room_no),
  CONSTRAINT fk_complaint_category FOREIGN KEY (category_id) REFERENCES category (category_id),
  CONSTRAINT fk_complaint_staff FOREIGN KEY (staff_id) REFERENCES staff (staff_id),
  CONSTRAINT ck_complaint_description CHECK (LENGTH(description) >= 10),
  CONSTRAINT ck_complaint_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED')),
  CONSTRAINT ck_complaint_resolved CHECK (
       (status = 'RESOLVED'  AND resolved_on IS NOT NULL)
    OR (status <> 'RESOLVED' AND resolved_on IS NULL)),
  CONSTRAINT ck_complaint_dates CHECK (resolved_on >= raised_on),
  CONSTRAINT ck_complaint_staff CHECK (status = 'OPEN' OR staff_id IS NOT NULL)
);
